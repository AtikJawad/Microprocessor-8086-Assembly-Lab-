DATA SEGMENT
    ARR DW 40H,10H,60H,20H,30H
    LEN EQU ($-ARR)/2
DATA ENDS

CODE SEGMENT
    ASSUME CS:CODE,DS:DATA

START:
    MOV AX,DATA
    MOV DS,AX

    MOV CX,LEN-1

OUTER:
    LEA SI,ARR
    MOV DX,CX

INNER:
    MOV AX,[SI]
    CMP AX,[SI+2]
    JBE NEXT

    XCHG AX,[SI+2]
    MOV [SI],AX

NEXT:
    ADD SI,2
    DEC DX
    JNZ INNER

    LOOP OUTER

    MOV AH,4CH
    INT 21H

CODE ENDS
END START
