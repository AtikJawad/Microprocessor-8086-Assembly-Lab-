DATA SEGMENT
    SOURCE DB 10H,20H,30H,40H,50H
    LEN EQU ($-SOURCE)
DATA ENDS

EXTRA SEGMENT
    DEST DB LEN DUP(?)
EXTRA ENDS

CODE SEGMENT
    ASSUME CS:CODE,DS:DATA,ES:EXTRA

START:
    MOV AX,DATA
    MOV DS,AX

    MOV AX,EXTRA
    MOV ES,AX

    LEA SI,SOURCE
    LEA DI,DEST

    MOV CX,LEN

UP:
    MOV AL,[SI]
    MOV ES:[DI],AL

    INC SI
    INC DI

    LOOP UP

    MOV AH,4CH
    INT 21H

CODE ENDS
END START
