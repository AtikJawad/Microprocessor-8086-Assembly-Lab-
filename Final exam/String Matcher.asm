DATA SEGMENT
    STR1 DB 'ATIK JAWAD$'
    STR2 DB 'ATIK JAWAD$'

    MES1 DB 13,10,'Strings are SAME$'
    MES2 DB 13,10,'Strings are NOT SAME$'
DATA ENDS

CODE SEGMENT
ASSUME CS:CODE,DS:DATA

START:
    MOV AX,DATA
    MOV DS,AX

    LEA SI,STR1
    LEA DI,STR2

COMPARE:
    MOV AL,[SI]
    MOV BL,[DI]

    CMP AL,BL
    JNE NOT_SAME

    CMP AL,'$'
    JE SAME

    INC SI
    INC DI
    JMP COMPARE

NOT_SAME:
    LEA DX,MES2
    MOV AH,09H
    INT 21H
    JMP EXIT

SAME:
    LEA DX,MES1
    MOV AH,09H
    INT 21H

EXIT:
    MOV AH,4CH
    INT 21H

CODE ENDS
END START
